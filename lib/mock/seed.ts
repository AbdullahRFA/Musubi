function at(day: number, hour: number, minute = 0) {
  return new Date(Date.UTC(2026, 10, day, hour, minute, 0)).toISOString();
}

function locate(name: string) {
  const place = placeByName(name);
  return { location: name, lat: place?.lat ?? null, lng: place?.lng ?? null };
}

